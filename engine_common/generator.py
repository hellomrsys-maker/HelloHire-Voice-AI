"""
generator.py — English-Parity Engine Scaffolding Generator.
===========================================================

Brings any language engine up to English-flagship parity by generating the files that
wire it to ``engine_common`` while PRESERVING every existing language-specific file.

For each engine it ensures the following exist (created only if missing, unless
``overwrite=True``):

  * ``<engine>/parity_orchestrator.py``     — subclass of BaseEngineOrchestrator.
  * ``<engine>/brain/task/parity_grammar_check.py``   — grammar check via base pipeline.
  * ``<engine>/brain/task/parity_translate.py``       — English-pivot translation task.
  * ``<engine>/brain/task/parity_summarize.py``       — extractive summariser.
  * ``<engine>/brain/task/parity_qa.py``              — English-pivot Q&A task.
  * ``<engine>/six_language_matrix/python/parity_matrix_bridge.py`` — matrix shim.
  * ``<engine>/train.py``                    — unified single-file trainer.
  * ``<engine>/train.js``                    — Node single-screen runner (AMSV 64B).
  * ``<engine>/parity_manifest.json``        — records parity status.

The generator NEVER deletes or rewrites hand-written engine files; parity files use a
``parity_`` prefix (or standard names only when absent) so existing behaviour is intact.
"""

