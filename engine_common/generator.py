def _sample_text(p: LanguageProfile) -> str:
    """A single short authentic sample sentence for this language."""
    inv = {v: k for k, v in p.to_english_lexicon.items() if v}
    term = p.sentence_terminators[0] if p.sentence_terminators else "."
    parts = [inv.get("the", ""), inv.get("cat", ""), inv.get("is", ""), inv.get("good", "")]
    words = [w for w in parts if w]
    if len(words) < 2:
        # Fall back to any lexicon entries.
        words = [k for k in list(p.to_english_lexicon.keys())[:3]]
    text = " ".join(words).strip()
    return (text + term) if text else ("sample" + term)


def _training_samples(p: LanguageProfile) -> List[str]:
    """A small authentic multi-sample training set assembled from the profile lexicon."""
    inv = {v: k for k, v in p.to_english_lexicon.items() if v}
    term = p.sentence_terminators[0] if p.sentence_terminators else "."
    samples = []

    def build(en_words):
        native = [inv.get(w, "") for w in en_words]
        native = [w for w in native if w]
        if len(native) >= 2:
            samples.append(" ".join(native) + term)

    build(["the", "cat", "is", "good"])
    build(["i", "read", "book"])
    build(["the", "house", "is", "good"])
    build(["i", "drink", "water"])
    if not samples:
        keys = list(p.to_english_lexicon.keys())
        if len(keys) >= 2:
            samples.append(" ".join(keys[:3]) + term)
        else:
            samples.append("sample" + term)
    return samples


