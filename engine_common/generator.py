def generate_native_lanes(engine_dir: str, overwrite: bool = False,
                          workspace_root: Optional[str] = None) -> Dict[str, str]:
    """Ensure all five native Six-Language-Matrix lanes exist for one engine."""
    root = workspace_root or WORKSPACE_ROOT
    profile = get_profile(engine_dir)
    base = os.path.join(root, engine_dir)
    actions: Dict[str, str] = {}
    for rel, content in native_lane_files(profile).items():
        actions[rel] = _write(os.path.join(base, rel), content, overwrite=overwrite)
    return actions


def generate_all_native_lanes(overwrite: bool = False,
                             workspace_root: Optional[str] = None) -> Dict[str, Dict[str, str]]:
    """Ensure every engine has the complete native Six-Language Matrix."""
    results: Dict[str, Dict[str, str]] = {}
    for engine_dir in sorted(LANGUAGE_REGISTRY):
        results[engine_dir] = generate_native_lanes(engine_dir, overwrite=overwrite,
                                                    workspace_root=workspace_root)
    return results
