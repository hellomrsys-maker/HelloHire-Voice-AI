def _translate_src(p: LanguageProfile) -> str:
    cp = p.class_prefix
    return f'''"""
{p.language_name} parity translation task. Implements English-FIRST translation:
{p.language_name} -> English via the shared English-pivot comprehension layer, and a
reverse English -> {p.language_name} gloss using the profile lexicon.
"""

from __future__ import annotations
from dataclasses import dataclass
from typing import Dict, List, Optional

from engine_common.english_pivot import EnglishPivotComprehension
from engine_common.language_profile import get_profile


@dataclass
class {cp}TranslationResult:
    source_text: str
    target_language: str
    translated_text: str
    english_pivot_text: str
    confidence: float


class {cp}ParityTranslator:
    def __init__(self) -> None:
        self.profile = get_profile("{p.engine_dir}")
        self.pivot = EnglishPivotComprehension(self.profile)
        self._en_to_native = {{v: k for k, v in self.profile.to_english_lexicon.items() if v}}

    def to_english(self, text: str) -> {cp}TranslationResult:
        res = self.pivot.comprehend(text)
        return {cp}TranslationResult(
            source_text=text, target_language="en",
            translated_text=res.canonical_english_order or res.english_projection,
            english_pivot_text=res.english_projection,
            confidence=res.comprehension_confidence,
        )

    def from_english(self, english_text: str) -> {cp}TranslationResult:
        words: List[str] = []
        for w in english_text.replace(".", " ").split():
            words.append(self._en_to_native.get(w.lower(), w))
        return {cp}TranslationResult(
            source_text=english_text, target_language="{p.iso_code}",
            translated_text=" ".join(words), english_pivot_text=english_text,
            confidence=0.75,
        )

    def translate(self, text: str, target_lang: str = "en") -> {cp}TranslationResult:
        return self.to_english(text) if target_lang == "en" else self.from_english(text)
'''


def _summarize_src(p: LanguageProfile) -> str:
    cp = p.class_prefix
    return f'''"""
{p.language_name} parity summarizer. Extractive sentence ranking scored through the
English-parity pipeline so the summary spine is understood in English first.
"""

from __future__ import annotations
from typing import Dict, Any, List, Optional

from amsv.python.amsv_embedded import AMSVEmbeddedView
from engine_common.base_orchestrator import BaseEngineOrchestrator
from engine_common.language_profile import get_profile


class {cp}ParitySummarizer:
    def __init__(self, amsv_view: Optional[AMSVEmbeddedView] = None) -> None:
        self.profile = get_profile("{p.engine_dir}")
        self.orch = BaseEngineOrchestrator(profile=self.profile, amsv_view=amsv_view)

    def _split_sentences(self, text: str) -> List[str]:
        buf, out = "", []
        for ch in text:
            buf += ch
            if ch in self.profile.sentence_terminators:
                out.append(buf.strip()); buf = ""
        if buf.strip():
            out.append(buf.strip())
        return [s for s in out if s]

    def summarize(self, text: str, max_sentences: int = 2) -> Dict[str, Any]:
        sentences = self._split_sentences(text)
        scored = []
        for s in sentences:
            out = self.orch.process(s)
            scored.append((out.overall_linguistic_score, s))
        scored.sort(key=lambda x: x[0], reverse=True)
        summary = " ".join(s for _, s in scored[:max_sentences])
        return {{
            "language": self.profile.language_name,
            "sentence_count": len(sentences),
            "summary": summary or text,
            "selected": [s for _, s in scored[:max_sentences]],
        }}
'''


def _qa_src(p: LanguageProfile) -> str:
    cp = p.class_prefix
    return f'''"""
{p.language_name} parity Q&A task. Understands both question and context in English
first (English-pivot), then selects the best-matching context sentence.
"""

from __future__ import annotations
from typing import Dict, Any, List

from engine_common.english_pivot import EnglishPivotComprehension
from engine_common.language_profile import get_profile


class {cp}ParityQA:
    def __init__(self) -> None:
        self.profile = get_profile("{p.engine_dir}")
        self.pivot = EnglishPivotComprehension(self.profile)

    def answer(self, question: str, context: str) -> Dict[str, Any]:
        q_tokens = set(self.pivot.comprehend(question).english_tokens)
        best, best_overlap, best_sent = None, -1, ""
        buf: List[str] = []
        cur = ""
        for ch in context:
            cur += ch
            if ch in self.profile.sentence_terminators:
                buf.append(cur.strip()); cur = ""
        if cur.strip():
            buf.append(cur.strip())
        for sent in buf or [context]:
            s_tokens = set(self.pivot.comprehend(sent).english_tokens)
            overlap = len(q_tokens & s_tokens)
            if overlap > best_overlap:
                best_overlap, best_sent = overlap, sent
        return {{
            "language": self.profile.language_name,
            "question": question,
            "answer": best_sent,
            "english_question": " ".join(sorted(q_tokens)),
            "token_overlap": max(0, best_overlap),
        }}
'''


