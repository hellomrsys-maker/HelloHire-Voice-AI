def generate_engine(engine_dir: str, overwrite: bool = False,
                    workspace_root: Optional[str] = None) -> Dict[str, str]:
    """Generate/refresh English-parity files for one engine. Returns per-file actions."""
    root = workspace_root or WORKSPACE_ROOT
    profile = get_profile(engine_dir)
    base = os.path.join(root, engine_dir)
    os.makedirs(base, exist_ok=True)

    actions: Dict[str, str] = {}

    # Ensure package __init__ files exist along the parity paths.
    _ensure_init(os.path.join(base, "__init__.py"))
    _ensure_init(os.path.join(base, "brain", "__init__.py"))
    _ensure_init(os.path.join(base, "brain", "task", "__init__.py"))
    _ensure_init(os.path.join(base, "six_language_matrix", "__init__.py"))

    for rel, builder in PARITY_FILES.items():
        # train.py/train.js should not clobber a hand-written flagship trainer.
        force = overwrite
        if rel in ("train.py", "train.js") and os.path.exists(os.path.join(base, rel)):
            force = False
        actions[rel] = _write(os.path.join(base, rel), builder(profile), overwrite=force)

    # Parity manifest.
    manifest = {
        "engine": engine_dir,
        "language": profile.language_name,
        "iso_code": profile.iso_code,
        "word_order": profile.word_order.value,
        "script": profile.script.value,
        "english_first": True,
        "parity_source": "engine_common",
        "parity_files": sorted(PARITY_FILES.keys()),
    }
    manifest_path = os.path.join(base, "parity_manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
    actions["parity_manifest.json"] = "written"
    return actions


def generate_all(overwrite: bool = False, exclude: Optional[List[str]] = None,
                 workspace_root: Optional[str] = None) -> Dict[str, Dict[str, str]]:
    """Generate English-parity files for every registered engine."""
    exclude = set(exclude or [])
    results: Dict[str, Dict[str, str]] = {}
    for engine_dir in sorted(LANGUAGE_REGISTRY):
        if engine_dir in exclude:
            continue
        results[engine_dir] = generate_engine(engine_dir, overwrite=overwrite,
                                              workspace_root=workspace_root)
    return results


